        #region Calls

        private String? BuildCall(IMethodSymbol method, Int32 skip, String? receiver, ISymbol owner, out String signature) =>
            BuildCall(method, skip, receiver, owner, out signature, out _);

        /// <summary>
        /// Writes the arguments of a call as BuildArgs makes them: the window where the method takes
        /// one first, optional parameters falling back to their defaults, a params array taking the
        /// remaining arguments, and the members of a [DomInitDict] read off one dictionary.
        /// </summary>
        private String? BuildCall(IMethodSymbol method, Int32 skip, String? receiver, ISymbol owner, out String signature, out Int32 required)
        {
            var parameters = method.Parameters;
            var arguments = new List<String>();
            var types = new List<String>();
            var lead = skip;
            var variadic = false;
            var index = skip;
            required = 0;
            signature = String.Empty;

            if (receiver != null)
            {
                arguments.Add(receiver);
            }

            if (index < parameters.Length && _model.Window != null && SymbolEqualityComparer.Default.Equals(parameters[index].Type, _model.Window))
            {
                arguments.Add("a.Window");
                index++;
                lead++;
            }

            var initDict = DomModel.GetAttributes(method, Names.DomInitDict).FirstOrDefault();
            var dictOffset = initDict != null && initDict.ConstructorArguments.Length > 0 && initDict.ConstructorArguments[0].Value is Int32 offset ? offset : -1;

            for (; index < parameters.Length; index++)
            {
                var parameter = parameters[index];

                if (parameter.RefKind != RefKind.None)
                {
                    _model.Skip(method, owner, $"the parameter '{parameter.Name}' is passed by reference");
                    return null;
                }

                if (!_model.IsAccessible(parameter.Type))
                {
                    _model.Skip(method, owner, $"the type of the parameter '{parameter.Name}' is not accessible");
                    return null;
                }

                var type = Fq(parameter.Type);

                if (dictOffset >= 0 && index >= dictOffset)
                {
                    if (index == dictOffset)
                    {
                        types.Add("typeof(object)");
                    }

                    arguments.Add($"a.GetMember<{type}>({dictOffset - lead}, {Literal(parameter.Name)}, {Fallback(parameter)})");
                    continue;
                }

                var position = index - lead;

                if (parameter.IsParams && parameter.Type is IArrayTypeSymbol array)
                {
                    if (_model.Node != null && SymbolEqualityComparer.Default.Equals(array.ElementType, _model.Node))
                    {
                        _usesRestNodes = true;
                        arguments.Add($"RestNodes(a, {position})");
                    }
                    else
                    {
                        _usesRest = true;
                        arguments.Add($"Rest<{Fq(array.ElementType)}>(a, {position})");
                    }

                    types.Add($"typeof({type})");
                    variadic = true;
                    continue;
                }

                arguments.Add(Value(parameter, position));
                types.Add($"typeof({type})");

                if (!parameter.IsOptional)
                {
                    required = types.Count;
                }
            }

            signature = types.Count == 0 && !variadic
                ? $"new {Signature}()"
                : $"new {Signature}({required}, {(variadic ? "true" : "false")}, new global::System.Type[] {{ {String.Join(", ", types)} }})";
            return String.Join(", ", arguments);
        }

        //  A function (or callback object, e.g. a NodeFilter with acceptNode) is converted by the
        //  engine like any other argument: its conversion binds "this", awaits a promise returned for
        //  a Task and keeps the identity of a listener, so that removing it removes what was added.
        private static String Value(IParameterSymbol parameter, Int32 position) =>
            parameter.IsOptional
                ? $"a.Get<{Fq(parameter.Type)}>({position}, {Fallback(parameter)})"
                : $"a.Get<{Fq(parameter.Type)}>({position})";

        /// <summary>
        /// The value script gets for what a member returned: a [DomReturnType] is honoured by an
        /// adapter class of that type taking the returned value (StaticNodeList for a NodeList).
        /// </summary>
        private String Box(String expression, ITypeSymbol type, IMethodSymbol? method)
        {
            var exposed = method != null
                ? DomModel.GetAttributes(method, Names.DomReturnType).Select(m => m.ConstructorArguments.Length > 0 ? m.ConstructorArguments[0].Value as ITypeSymbol : null).FirstOrDefault()
                : null;

            if (exposed != null && !DomModel.IsAssignable(type, exposed))
            {
                var adapter = FindAdapter(exposed, type);

                if (adapter != null)
                {
                    return $"({expression}) is {Fq(type)} r ? (object)new {Fq(adapter)}(r) : null";
                }

                _model.Skip(method!, method!.ContainingType, $"no class adapting it to '{exposed.Name}' is found, so the value keeps its own type");
            }

            var given = GetGivenConversion(type);

            if (given != null)
            {
                return $"({expression}) is {Fq(type)} g ? (object)({Fq(given)})g : null";
            }

            return $"(object)({expression})";
        }

        /// <summary>
        /// Gets the type a WebIDL union (a class converting from several types) is given to script
        /// as: the one its implicit conversion away converts to.
        /// </summary>
        public static ITypeSymbol? GetGivenConversion(ITypeSymbol type)
        {
            if (type.TypeKind != TypeKind.Class || type.SpecialType == SpecialType.System_String)
            {
                return null;
            }

            var conversions = type.GetMembers("op_Implicit").OfType<IMethodSymbol>().Where(m => m.IsStatic && m.Parameters.Length == 1).ToList();

            if (!conversions.Any(m => SymbolEqualityComparer.Default.Equals(m.ReturnType, type)))
            {
                return null;
            }

            return conversions.FirstOrDefault(m => !SymbolEqualityComparer.Default.Equals(m.ReturnType, type) && SymbolEqualityComparer.Default.Equals(m.Parameters[0].Type, type))?.ReturnType;
        }

        private INamedTypeSymbol? FindAdapter(ITypeSymbol exposed, ITypeSymbol returned) =>
            _model.Classes.FirstOrDefault(m => !m.IsAbstract && DomModel.IsAssignable(m, exposed) &&
                m.InstanceConstructors.Any(c => c.Parameters.Length == 1 && _model.IsAccessible(c) && DomModel.IsAssignable(returned, c.Parameters[0].Type)));

        #endregion

        #region Receivers

        //  An interface member is invoked through its interface, so that one of the same name on
        //  another interface of the type cannot be picked instead, and an explicitly re-declared
        //  one (IHtmlCollection<T> naming IReadOnlyList<T>'s indexer) through the one it stands for.
        private static String Target(INamedTypeSymbol receiver, ISymbol member, out String name)
        {
            var implemented = DomModel.Implemented(member);

            name = implemented is IPropertySymbol property && property.IsIndexer ? "this" : implemented.Name;
            var owner = implemented.ContainingType;
            return SymbolEqualityComparer.Default.Equals(owner, receiver) ? "t" : $"(({Fq(owner)})t)";
        }

        private static String Access(INamedTypeSymbol receiver, ISymbol member)
        {
            var target = Target(receiver, member, out var name);
            return $"{target}.{name}";
        }

        private static String Index(INamedTypeSymbol receiver, IPropertySymbol indexer, String index, Boolean box = true, Boolean raw = false)
        {
            var target = Target(receiver, indexer, out _);
            var access = $"{target}[{index}]";
            return box && !raw ? $"(object){access}" : access;
        }

        private static String ExtensionReceiver(INamedTypeSymbol receiver, IMethodSymbol method)
        {
            var parameter = method.Parameters[0].Type;
            return DomModel.IsAssignable(receiver, parameter) ? "t" : $"(({Fq(parameter)})(object)t)";
        }

        #endregion

        #region Literals

        public static String Fq(ITypeSymbol type) => type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(Format);

        private static String Literal(String value) => SymbolDisplay.FormatLiteral(value, true);

        private static String Number(Double value) =>
            Double.IsNaN(value) ? "double.NaN" : Double.IsPositiveInfinity(value) ? "double.PositiveInfinity" : Double.IsNegativeInfinity(value) ? "double.NegativeInfinity" :
            value.ToString("R", CultureInfo.InvariantCulture) + "D";

        private static String Fallback(IParameterSymbol parameter)
        {
            var type = Fq(parameter.Type);

            if (!parameter.IsOptional || !parameter.HasExplicitDefaultValue || parameter.ExplicitDefaultValue == null)
            {
                return $"default({type})";
            }

            var value = parameter.ExplicitDefaultValue;

            switch (value)
            {
                case String text:
                    return Literal(text);
                case Boolean flag:
                    return flag ? "true" : "false";
                case Char c:
                    return SymbolDisplay.FormatLiteral(c, true);
                case Double d:
                    return $"({type})({Number(d)})";
                case Single f:
                    return $"({type})({Number(f)})";
                default:
                    return $"({type})({Convert.ToString(value, CultureInfo.InvariantCulture)})";
            }
        }

        #endregion
    }
