namespace AngleSharp.Generators
{
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.CSharp;
    using System;
    using System.Collections.Generic;
    using System.Globalization;
    using System.Linq;
    using System.Text;

    /// <summary>
    /// Writes the registration a <see cref="DomModel"/> describes.
    /// </summary>
    /// <remarks>
    /// Every declaration becomes a strongly typed lambda, so nothing is reflected over at run time
    /// and what is registered is what the trimmer keeps. Each type gets a method of its own: one
    /// method holding thousands of lambdas would be costly to JIT for what is run once.
    /// </remarks>
    sealed class DomEmitter
    {
        private const String Registry = "global::AngleSharp.Scripting.DomRegistry";
        private const String Signature = "global::AngleSharp.Scripting.DomSignature";
        private const String Arguments = "global::AngleSharp.Scripting.DomArguments";

        private static readonly SymbolDisplayFormat Format = SymbolDisplayFormat.FullyQualifiedFormat
            .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers | SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

        private readonly DomModel _model;
        private readonly List<String> _methods = new List<String>();
        private Boolean _usesRest;
        private Boolean _usesRestNodes;

        public DomEmitter(DomModel model)
        {
            _model = model;
        }

        public String Emit(String fullName)
        {
            var dot = fullName.LastIndexOf('.');
            var ns = dot > 0 ? fullName.Substring(0, dot) : null;
            var name = dot > 0 ? fullName.Substring(dot + 1) : fullName;
            var literals = new List<INamedTypeSymbol>();
            var standalone = new List<KeyValuePair<String, INamedTypeSymbol>>();
            var owned = new List<KeyValuePair<String, KeyValuePair<String, Double>>>();
            _model.ClassifyEnums(literals, standalone, owned);

            foreach (var symbol in _model.Namespaces)
            {
                Add(EmitNamespace(symbol, owned));
            }

            foreach (var type in _model.Types)
            {
                Add(EmitType(type));
            }

            foreach (var body in EmitForeignContributions())
            {
                Add(body);
            }

            Add(EmitConstants(standalone, owned));
            Add(EmitLiterals(literals));
            Add(EmitConstructorFunctions());
            Add(EmitInstances());

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Generated by AngleSharp.Generators from the DOM attributes of this assembly.");
            sb.AppendLine("#nullable disable");
            sb.AppendLine("#pragma warning disable");

            if (ns != null)
            {
                sb.Append("namespace ").AppendLine(ns);
                sb.AppendLine("{");
            }

            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Declares the DOM of this assembly without reflection, see <see cref=\"global::AngleSharp.Scripting.DomRegistration\"/>.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"AngleSharp.Generators\", \"1.0.0\")]");
            sb.Append("    public static partial class ").AppendLine(name);
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// Declares the DOM of this assembly on the given registry.");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        /// <param name=\"registry\">The registry to declare the DOM on.</param>");
            sb.Append("        public static void Register(").Append(Registry).AppendLine(" registry)");
            sb.AppendLine("        {");

            for (var i = 0; i < _methods.Count; i++)
            {
                sb.Append("            R").Append(i).AppendLine("(registry);");
            }

            sb.AppendLine("        }");

            for (var i = 0; i < _methods.Count; i++)
            {
                sb.AppendLine();
                sb.Append("        private static void R").Append(i).Append('(').Append(Registry).AppendLine(" registry)");
                sb.AppendLine("        {");
                sb.Append(_methods[i]);
                sb.AppendLine("        }");
            }

            if (_usesRest)
            {
                sb.AppendLine();
                sb.Append("        private static T[] Rest<T>(").Append(Arguments).AppendLine(" a, int start)");
                sb.AppendLine("        {");
                sb.AppendLine("            var items = new T[global::System.Math.Max(0, a.Length - start)];");
                sb.AppendLine("            for (var i = 0; i < items.Length; i++) { items[i] = a.Get<T>(start + i); }");
                sb.AppendLine("            return items;");
                sb.AppendLine("        }");
            }

            if (_usesRestNodes)
            {
                //  a WebIDL (Node or DOMString)... takes text as a text node, as BuildArgs does
                var node = Fq(_model.Node!);
                sb.AppendLine();
                sb.Append("        private static ").Append(node).Append("[] RestNodes(").Append(Arguments).AppendLine(" a, int start)");
                sb.AppendLine("        {");
                sb.Append("            var items = new ").Append(node).AppendLine("[global::System.Math.Max(0, a.Length - start)];");
                sb.AppendLine("            for (var i = 0; i < items.Length; i++)");
                sb.AppendLine("            {");
                sb.AppendLine("                var value = a.Get<object>(start + i);");
                sb.Append("                items[i] = value is string || value is double || value is bool || value is int ? a.Window.Document.CreateTextNode(a.Get<string>(start + i)) : a.Get<").Append(node).AppendLine(">(start + i);");
                sb.AppendLine("            }");
                sb.AppendLine("            return items;");
                sb.AppendLine("        }");
            }

            sb.AppendLine("    }");

            if (ns != null)
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }

        private void Add(String? body)
        {
            if (!String.IsNullOrEmpty(body))
            {
                _methods.Add(body!);
            }
        }

        #region Types

        private String EmitType(DomType type)
        {
            _model.Analyze(type);
            var sb = new StringBuilder();
            var symbol = type.Symbol;
            sb.Append("            ").Append(Declare(type));

            if (type.Base != null)
            {
                Chain(sb, $"Inherits<{Fq(type.Base.Symbol)}>()");
            }

            foreach (var mixin in type.Mixins)
            {
                Chain(sb, $"Includes<{Fq(mixin.Symbol)}>()");
            }

            if (type.NoInterfaceObject)
            {
                Chain(sb, "WithoutInterfaceObject()");
            }
            else if (!type.IsVariant && !type.Symbol.IsGenericType)
            {
                foreach (var alias in type.Names.Skip(1))
                {
                    Chain(sb, $"Alias({Literal(alias)})");
                }

                var ns = type.Exposed.FirstOrDefault(_model.IsNamespace);

                if (ns != null)
                {
                    Chain(sb, $"InNamespace({Literal(ns)})");
                }
            }

            if (symbol.TypeKind == TypeKind.Class && !type.NoInterfaceObject && !type.IsMixin)
            {
                EmitConstructors(sb, type);
                EmitStatics(sb, symbol, symbol, (name, call) => Chain(sb, call));
            }

            var receiver = symbol;

            foreach (var entry in _model.GetOwnMembers(type))
            {
                EmitMember(sb, type, receiver, entry.Key, entry.Value, null);
            }

            EmitIndexers(sb, type, _model.Simulate(type));
            sb.AppendLine(";");
            return sb.ToString();
        }

        private static String Declare(DomType type) =>
            $"registry.{(type.IsMixin ? "Mixin" : "Type")}<{Fq(type.Symbol)}>({Literal(type.Name)})";

        private static void Chain(StringBuilder sb, String call) =>
            sb.AppendLine().Append("                .").Append(call);

        private void EmitConstructors(StringBuilder sb, DomType type)
        {
            var symbol = type.Symbol;

            foreach (var constructor in symbol.InstanceConstructors)
            {
                if (!DomModel.Has(constructor, Names.DomConstructor))
                {
                    continue;
                }

                if (symbol.IsAbstract || !_model.IsAccessible(constructor))
                {
                    _model.Skip(constructor, symbol, "the constructor is not accessible");
                    continue;
                }

                var call = BuildCall(constructor, 0, null, symbol, out var signature);

                if (call != null)
                {
                    Chain(sb, $"Constructor(a => new {Fq(symbol)}({call}), {signature})");
                }
            }
        }

        /// <summary>
        /// The static members of a class or namespace, found on its interface object.
        /// </summary>
        private void EmitStatics(StringBuilder sb, INamedTypeSymbol type, ISymbol owner, Action<String, String> chain)
        {
            foreach (var member in _model.GetStaticMembers(type))
            {
                var name = Literal(member.Name);

                if (member.Property != null)
                {
                    var property = member.Property;

                    if (!_model.IsAccessible(property) || !_model.IsAccessible(property.Type) || property.GetMethod == null)
                    {
                        _model.Skip(property, owner, "the static attribute is not accessible");
                        continue;
                    }

                    var target = $"{Fq(property.ContainingType)}.{property.Name}";
                    var setter = property.SetMethod != null && _model.IsAccessible(property.SetMethod) ? $", v => {target} = v" : String.Empty;
                    chain(member.Name, $"StaticProperty<{Fq(property.Type)}>({name}, () => {target}{setter})");
                }
                else if (member.Getter != null || member.Setter != null)
                {
                    var getter = member.Getter;
                    var setter = member.Setter;

                    //  either both take the window first (a setting of it) or neither does
                    var withWindow = getter != null && _model.TakesWindow(getter);
                    var expected = withWindow ? 1 : 0;

                    if (getter == null || getter.Parameters.Length != expected || setter != null && (setter.Parameters.Length != expected + 1 || _model.TakesWindow(setter) != withWindow))
                    {
                        _model.Skip(getter ?? setter!, owner, "a static accessor taking arguments beside the window has no registered form");
                        continue;
                    }

                    if (withWindow)
                    {
                        var set = setter != null ? $", (w, v) => {Fq(setter.ContainingType)}.{setter.Name}(w, v)" : String.Empty;
                        chain(member.Name, $"StaticProperty<{Fq(getter.ReturnType)}>({name}, w => {Fq(getter.ContainingType)}.{getter.Name}(w){set})");
                    }
                    else
                    {
                        var set = setter != null ? $", v => {Fq(setter.ContainingType)}.{setter.Name}(v)" : String.Empty;
                        chain(member.Name, $"StaticProperty<{Fq(getter.ReturnType)}>({name}, () => {Fq(getter.ContainingType)}.{getter.Name}(){set})");
                    }
                }
                else
                {
                    foreach (var method in member.Overloads)
                    {
                        if (!_model.IsAccessible(method))
                        {
                            _model.Skip(method, owner, "the static operation is not accessible");
                            continue;
                        }

                        var call = BuildCall(method, 0, null, owner, out var signature);

                        if (call != null)
                        {
                            var invoke = $"{Fq(method.ContainingType)}.{method.Name}({call})";
                            var body = method.ReturnsVoid ? $"{{ {invoke}; return null; }}" : $"{{ return {Box(invoke, method.ReturnType, method)}; }}";
                            chain(member.Name, $"Static({name}, a => {body}, {signature})");
                        }
                    }
                }
            }
        }

        private void EmitIndexers(StringBuilder sb, DomType type, Simulation sim)
        {
            var receiver = type.Symbol;

            if (sim.NumericIndexer != null && _model.IsAccessible(sim.NumericIndexer))
            {
                Chain(sb, $"Indexer((t, i) => {Index(receiver, sim.NumericIndexer, "i")})");
            }

            if (sim.Collection == true && sim.CollectionIndexer != null && sim.CollectionLength != null &&
                _model.IsAccessible(sim.CollectionIndexer) && _model.IsAccessible(sim.CollectionLength))
            {
                Chain(sb, $"Collection(t => {Access(receiver, sim.CollectionLength)}, (t, i) => {Index(receiver, sim.CollectionIndexer, "i")})");
            }

            if (sim.NamedGetter != null && _model.IsAccessible(sim.NamedGetter))
            {
                var getter = sim.NamedGetter;
                var type2 = Fq(getter.Type);
                var setter = sim.NamedSetter != null && sim.NamedSetter.SetMethod != null && _model.IsAccessible(sim.NamedSetter.SetMethod) &&
                    SymbolEqualityComparer.Default.Equals(sim.NamedSetter.Type, getter.Type)
                    ? $", (t, n, v) => {Index(receiver, sim.NamedSetter, "n", false)} = v"
                    : String.Empty;
                Chain(sb, $"NamedIndexer<{type2}>((t, n) => {Index(receiver, getter, "n", false)}{setter})");
            }
        }

        #endregion

        #region Members

        private void EmitMember(StringBuilder sb, DomType type, INamedTypeSymbol receiver, String name, Member member, List<Callable>? only)
        {
            var owner = type.Symbol;
            var literal = Literal(name);

            switch (member.Kind)
            {
                case MemberKind.Property:
                {
                    var property = member.Property!;

                    if (!_model.IsAccessible(property) || !_model.IsAccessible(property.Type) || DomModel.IsObsoleteError(property))
                    {
                        _model.Skip(property, owner, "the attribute is not accessible");
                        return;
                    }

                    var value = Fq(property.Type);
                    var getter = property.GetMethod != null && _model.IsAccessible(property.GetMethod) ? $"t => {Access(receiver, property)}" : $"t => default({value})";

                    if (member.ForwardTo != null)
                    {
                        Chain(sb, $"ForwardingProperty<{value}>({literal}, {getter}, {Literal(member.ForwardTo)})");
                    }
                    else
                    {
                        var setter = property.SetMethod != null && _model.IsAccessible(property.SetMethod) ? $", (t, v) => {Access(receiver, property)} = v" : ", null";
                        var flags = member.SameObject ? ", global::AngleSharp.Scripting.DomPropertyFlags.SameObject" : String.Empty;
                        Chain(sb, $"Property<{value}>({literal}, {getter}{(setter == ", null" && flags.Length == 0 ? String.Empty : setter)}{flags})");
                    }

                    break;
                }
                case MemberKind.Method:
                {
                    foreach (var callable in only ?? member.Overloads)
                    {
                        EmitCallable(sb, owner, receiver, literal, callable);
                    }

                    break;
                }
                case MemberKind.Event:
                {
                    var ev = member.Event!;

                    if (!SymbolEqualityComparer.Default.Equals(ev.Type, _model.EventHandler) || !_model.IsAccessible(ev))
                    {
                        _model.Skip(ev, owner, "only accessible events of DomEventHandler are event handler attributes");
                        return;
                    }

                    var target = Access(receiver, ev);
                    Chain(sb, $"EventHandler({literal}, (t, h) => {target} += h, (t, h) => {target} -= h)");
                    break;
                }
                case MemberKind.ExtensionProperty:
                {
                    var getter = member.Getter;
                    var setter = member.Setter;
                    var any = (getter ?? setter)!;

                    if (getter != null && !_model.IsAccessible(getter) || setter != null && !_model.IsAccessible(setter))
                    {
                        _model.Skip(any, owner, "the attribute is not accessible");
                        return;
                    }

                    var valueType = getter != null ? getter.ReturnType : setter!.Parameters[setter.Parameters.Length - 1].Type;
                    var value = Fq(valueType);
                    var read = getter != null ? $"t => {Fq(getter.ContainingType)}.{getter.Name}({ExtensionReceiver(receiver, getter)})" : $"t => default({value})";

                    if (member.ForwardTo != null)
                    {
                        Chain(sb, $"ForwardingProperty<{value}>({literal}, {read}, {Literal(member.ForwardTo)})");
                    }
                    else if (setter != null && setter.Parameters.Length == 2)
                    {
                        var argument = SymbolEqualityComparer.Default.Equals(setter.Parameters[1].Type, valueType) ? "v" : $"({Fq(setter.Parameters[1].Type)})(object)v";
                        Chain(sb, $"Property<{value}>({literal}, {read}, (t, v) => {Fq(setter.ContainingType)}.{setter.Name}({ExtensionReceiver(receiver, setter)}, {argument}))");
                    }
                    else
                    {
                        Chain(sb, $"Property<{value}>({literal}, {read})");
                    }

                    break;
                }
                case MemberKind.ExtensionEvent:
                {
                    var adder = member.Adder!;
                    var remover = member.Remover!;
                    Chain(sb, $"EventHandler({literal}, (t, h) => {Fq(adder.ContainingType)}.{adder.Name}({ExtensionReceiver(receiver, adder)}, h), (t, h) => {Fq(remover.ContainingType)}.{remover.Name}({ExtensionReceiver(receiver, remover)}, h))");
                    break;
                }
                case MemberKind.Stringifier:
                    Chain(sb, $"Method({literal}, (t, a) => {{ return t.ToString(); }}, new {Signature}())");
                    break;
            }
        }

        private void EmitCallable(StringBuilder sb, INamedTypeSymbol owner, INamedTypeSymbol receiver, String literal, Callable callable)
        {
            switch (callable.Kind)
            {
                case CallableKind.PropertyGetter:
                {
                    var property = (IPropertySymbol)callable.Symbol;

                    if (!_model.IsAccessible(property))
                    {
                        _model.Skip(property, owner, "the operation is not accessible");
                        return;
                    }

                    Chain(sb, $"Method({literal}, (t, a) => {{ return {Box(Access(receiver, property), property.Type, null)}; }}, new {Signature}())");
                    return;
                }
                case CallableKind.IndexerGetter:
                {
                    var property = (IPropertySymbol)callable.Symbol;

                    if (!_model.IsAccessible(property) || property.Parameters.Length != 1)
                    {
                        _model.Skip(property, owner, "the operation is not accessible");
                        return;
                    }

                    var parameter = property.Parameters[0];
                    var index = $"a.Get<{Fq(parameter.Type)}>(0)";
                    Chain(sb, $"Method({literal}, (t, a) => {{ return {Box(Index(receiver, property, index, false, true), property.Type, null)}; }}, new {Signature}(1, false, new global::System.Type[] {{ typeof({Fq(parameter.Type)}) }}))");
                    return;
                }
            }

            var method = (IMethodSymbol)callable.Symbol;

            if (!_model.IsAccessible(method) || DomModel.IsObsoleteError(method))
            {
                _model.Skip(method, owner, "the operation is not accessible");
                return;
            }

            String? call;
            String signature;
            String invoke;

            if (callable.IsExtension)
            {
                call = BuildCall(method, 1, ExtensionReceiver(receiver, method), owner, out signature);
                invoke = $"{Fq(method.ContainingType)}.{method.Name}({call})";
            }
            else
            {
                call = BuildCall(method, 0, null, owner, out signature);
                invoke = $"{Target(receiver, method, out var name)}.{name}({call})";
            }

            if (call == null)
            {
                return;
            }

            var body = method.ReturnsVoid ? $"{{ {invoke}; }}" : $"{{ return {Box(invoke, method.ReturnType, method)}; }}";
            Chain(sb, $"Method({literal}, (t, a) => {body}, {signature})");
        }

        /// <summary>
        /// The members a library adds to a type of another library (rule 7: what the type
        /// declares itself is kept), and the overloads it adds to one of its operations.
        /// </summary>
        private IEnumerable<String> EmitForeignContributions()
        {
            var targets = new List<DomType>();

            foreach (var holder in _model.Holders)
            {
                foreach (var target in DomModel.GetAttributes(holder, Names.DomExposed).Select(m => m.ConstructorArguments.Length > 0 ? m.ConstructorArguments[0].Value as String : null))
                {
                    if (target == null || _model.IsNamespace(target))
                    {
                        continue;
                    }

                    var type = _model.FindByName(target);

                    if (type == null)
                    {
                        _model.Unresolved(holder, target);
                    }
                    else if (!type.IsOwn && !targets.Contains(type))
                    {
                        targets.Add(type);
                    }
                }
            }

            foreach (var type in targets)
            {
                _model.Analyze(type);
                var sim = _model.Simulate(type);
                var sb = new StringBuilder();
                sb.Append("            ").Append(Declare(type));
                var any = false;

                foreach (var name in sim.Order)
                {
                    var member = sim.Members[name];

                    if (member.FromExtension)
                    {
                        EmitMember(sb, type, type.Symbol, name, member, null);
                        any = true;
                    }
                    else if (member.Extended)
                    {
                        //  Overloads accumulate on a set the type declared itself; one it inherits
                        //  has to be declared on it in full, as a declaration of its own hides it.
                        var own = type.Flatten!.Contains(member.Owner);
                        EmitMember(sb, type, type.Symbol, name, member, own ? member.Overloads.Where(m => m.IsExtension).ToList() : null);
                        any = true;
                    }
                }

                if (any)
                {
                    sb.AppendLine(";");
                    yield return sb.ToString();
                }
            }
        }

        #endregion

        #region Namespaces, constants and the rest

        private String EmitNamespace(INamedTypeSymbol symbol, List<KeyValuePair<String, KeyValuePair<String, Double>>> owned)
        {
            var name = DomModel.GetDomNames(symbol)[0];
            var sb = new StringBuilder();
            sb.Append("            registry.Namespace(").Append(Literal(name)).Append(')');
            EmitStatics(sb, symbol, symbol, (member, call) => Chain(sb, call));

            foreach (var constant in owned.Where(m => m.Key == name))
            {
                Chain(sb, $"Constant({Literal(constant.Value.Key)}, {Number(constant.Value.Value)})");
            }

            sb.AppendLine(";");
            return sb.ToString();
        }

        private String EmitConstants(List<KeyValuePair<String, INamedTypeSymbol>> standalone, List<KeyValuePair<String, KeyValuePair<String, Double>>> owned)
        {
            var sb = new StringBuilder();

            foreach (var entry in standalone)
            {
                sb.Append("            registry.Constants(").Append(Literal(entry.Key)).Append(')');

                foreach (var field in entry.Value.GetMembers().OfType<IFieldSymbol>().Where(m => m.HasConstantValue))
                {
                    var constant = DomModel.GetDomNames(field).FirstOrDefault();

                    if (constant != null)
                    {
                        Chain(sb, $"Constant({Literal(constant)}, {Number(Convert.ToDouble(field.ConstantValue))})");
                    }
                }

                sb.AppendLine(";");
            }

            foreach (var group in owned.GroupBy(m => m.Key))
            {
                if (_model.IsNamespace(group.Key))
                {
                    continue;
                }

                var type = _model.FindByName(group.Key);

                if (type == null || !_model.IsAccessible(type.Symbol))
                {
                    continue;
                }

                sb.Append("            ").Append(Declare(type));

                foreach (var constant in group)
                {
                    Chain(sb, $"Constant({Literal(constant.Value.Key)}, {Number(constant.Value.Value)})");
                }

                sb.AppendLine(";");
            }

            return sb.ToString();
        }

        private String EmitLiterals(List<INamedTypeSymbol> literals)
        {
            var sb = new StringBuilder();

            foreach (var type in literals)
            {
                if (!_model.IsAccessible(type))
                {
                    continue;
                }

                sb.Append("            registry.Literals<").Append(Fq(type)).Append(">()");

                foreach (var field in type.GetMembers().OfType<IFieldSymbol>().Where(m => m.HasConstantValue))
                {
                    var literal = DomModel.GetDomNames(field).FirstOrDefault();

                    if (literal != null)
                    {
                        Chain(sb, $"Literal({Fq(type)}.{field.Name}, {Literal(literal)})");
                    }
                }

                sb.AppendLine(";");
            }

            return sb.ToString();
        }

        private String EmitConstructorFunctions()
        {
            var sb = new StringBuilder();

            foreach (var type in _model.Holders.Concat(_model.Classes).Concat(_model.Namespaces).Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default))
            {
                foreach (var method in type.GetMembers().OfType<IMethodSymbol>())
                {
                    var name = DomModel.GetString(method, Names.DomConstructorFunction);

                    if (name == null || !method.IsStatic || method.ReturnsVoid || method.ReturnType.IsValueType)
                    {
                        continue;
                    }

                    var call = BuildCall(method, 0, null, type, out _, out var required);

                    if (call != null)
                    {
                        sb.Append("            registry.ConstructorFunction<").Append(Fq(method.ReturnType)).Append(">(").Append(Literal(name))
                            .Append(", a => ").Append(Fq(type)).Append('.').Append(method.Name).Append('(').Append(call).Append("), ")
                            .Append(required.ToString(CultureInfo.InvariantCulture)).AppendLine(");");
                    }
                }
            }

            return sb.ToString();
        }

        private String EmitInstances()
        {
            var sb = new StringBuilder();

            foreach (var type in _model.Classes)
            {
                foreach (var attribute in DomModel.GetAttributes(type, Names.DomInstance))
                {
                    if (attribute.ConstructorArguments.Length == 0 || !(attribute.ConstructorArguments[0].Value is String name))
                    {
                        continue;
                    }

                    var constructor = type.InstanceConstructors.FirstOrDefault(m => m.Parameters.Length == 0);

                    if (type.IsAbstract || constructor == null || !_model.IsAccessible(constructor))
                    {
                        _model.Skip(type, type, "a window instance needs an accessible constructor without parameters");
                        continue;
                    }

                    sb.Append("            registry.Instance(").Append(Literal(name)).Append(", w => new ").Append(Fq(type)).AppendLine("());");
                }
            }

            return sb.ToString();
        }

